// Regenerates src/abis.ts from the Foundry build output so the UI never drifts
// from the contracts. Run after `forge build` in ../contracts:
//   bun run sync-abis
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../contracts/out");

function abiOf(name: string): unknown[] {
  const file = resolve(out, `${name}.sol/${name}.json`);
  const json = JSON.parse(readFileSync(file, "utf8")) as { abi?: unknown[] };
  if (!json.abi) throw new Error(`No ABI in ${file}. Run forge build first.`);
  return json.abi;
}

const ERC20_ABI = [
  { type: "function", name: "approve", inputs: [{ name: "spender", type: "address" }, { name: "amount", type: "uint256" }], outputs: [{ name: "", type: "bool" }], stateMutability: "nonpayable" },
  { type: "function", name: "allowance", inputs: [{ name: "owner", type: "address" }, { name: "spender", type: "address" }], outputs: [{ name: "", type: "uint256" }], stateMutability: "view" },
  { type: "function", name: "balanceOf", inputs: [{ name: "account", type: "address" }], outputs: [{ name: "", type: "uint256" }], stateMutability: "view" },
];

const body = [
  "// GENERATED by scripts/sync-abis.ts from contracts/out. Do not edit by hand.",
  `export const ACP_ABI = ${JSON.stringify(abiOf("AgenticCommerce"))} as const;`,
  "",
  `export const ERC20_ABI = ${JSON.stringify(ERC20_ABI)} as const;`,
  "",
  `export const BOND_HOOK_ABI = ${JSON.stringify(abiOf("BondHook"))} as const;`,
  "",
].join("\n");

writeFileSync(resolve(here, "../src/abis.ts"), body);
console.log("abis.ts regenerated");
